-- =========================
-- 12) 赛事结果录入 RPC（参考实现）
-- =========================
-- 前端（tournament.js）调用：staff_set_tournament_result(p_match_id, p_score_a, p_score_b, p_forfeit)。
-- p_forfeit 取值：'none'（正常比分）、'a'（A 方弃权）、'b'（B 方弃权）、'both'（双方弃权）。
-- 只要有任何一方弃权，本场就不会写入 public.matches，因此不计入积分；但仍会记录胜负
-- （双方弃权则无胜者）并按签位推进。清除结果时 p_score_a/p_score_b 传 null 且 p_forfeit='none'。
--
-- 注意：线上可能已部署同名函数。覆盖前请先对比线上定义，避免丢失线上特有的推进逻辑；
-- 若线上签名不同，本函数会作为重载存在，请以线上版本为准并仅补充 p_forfeit 参数。
-- 本节可单独执行：先补齐 forfeit 列与约束（幂等），再替换函数。
alter table public.tournament_matches add column if not exists forfeit text not null default 'none';
alter table public.tournament_matches drop constraint if exists tournament_matches_forfeit_check;
alter table public.tournament_matches add constraint tournament_matches_forfeit_check check (forfeit in ('none','a','b','both'));

-- 旧版（如 3 参数版本）必须先删除：否则新旧签名会同时存在，PostgREST 调用时会报
-- “Could not find the function ... in the schema cache” 之类的重载歧义错误。
do $$
declare
  r record;
begin
  for r in
    select p.oid::regprocedure as sig
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'staff_set_tournament_result'
  loop
    execute format('drop function %s', r.sig);
  end loop;
end;
$$;

create or replace function public.staff_set_tournament_result(
  p_match_id uuid,
  p_score_a integer default null,
  p_score_b integer default null,
  p_forfeit text default 'none'
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_match public.tournament_matches%rowtype;
  v_competition text;
  v_forfeit text := coalesce(nullif(trim(p_forfeit), ''), 'none');
  v_winner uuid;
  v_loser uuid;
  v_rating_match_id uuid;
begin
  if not private.is_staff() then
    raise exception '没有赛事管理权限。';
  end if;
  if v_forfeit not in ('none','a','b','both') then
    raise exception '无效的弃权选项。';
  end if;

  select * into v_match from public.tournament_matches where id = p_match_id for update;
  if not found then
    raise exception '比赛不存在。';
  end if;
  if v_match.player_a_id is null or v_match.player_b_id is null then
    raise exception '比赛双方尚未确定，无法录入结果。';
  end if;

  -- 撤销此前由本场生成的积分比赛（修改结果或清除结果时）。
  if v_match.rating_match_id is not null then
    update public.matches set status = 'cancelled'
     where id = v_match.rating_match_id and status <> 'cancelled';
  end if;

  -- 清除结果：把本场退回“待进行”，并撤回已推进到下一轮的选手。
  if p_score_a is null and p_score_b is null and v_forfeit = 'none' then
    if v_match.winner_id is not null and v_match.next_match_id is not null then
      if v_match.next_slot = 2 then
        update public.tournament_matches set player_b_id = null, updated_at = now()
         where id = v_match.next_match_id and player_b_id = v_match.winner_id;
      else
        update public.tournament_matches set player_a_id = null, updated_at = now()
         where id = v_match.next_match_id and player_a_id = v_match.winner_id;
      end if;
    end if;
    update public.tournament_matches
       set status = 'scheduled', score_a = null, score_b = null, forfeit = 'none',
           winner_id = null, rating_match_id = null, updated_at = now()
     where id = v_match.id;
    return;
  end if;

  -- 修改结果时，先把上一场的胜者/负者从下一轮签位撤回，避免残留。
  if v_match.winner_id is not null and v_match.next_match_id is not null then
    if v_match.next_slot = 2 then
      update public.tournament_matches set player_b_id = null, updated_at = now()
       where id = v_match.next_match_id and player_b_id = v_match.winner_id;
    else
      update public.tournament_matches set player_a_id = null, updated_at = now()
       where id = v_match.next_match_id and player_a_id = v_match.winner_id;
    end if;
  end if;
  if v_match.winner_id is not null and v_match.next_loss_match_id is not null then
    if v_match.next_loss_slot = 2 then
      update public.tournament_matches set player_b_id = null, updated_at = now()
       where id = v_match.next_loss_match_id and player_b_id = v_match.winner_id;
    else
      update public.tournament_matches set player_a_id = null, updated_at = now()
       where id = v_match.next_loss_match_id and player_a_id = v_match.winner_id;
    end if;
  end if;

  if v_forfeit = 'none' then
    if p_score_a is null or p_score_b is null then
      raise exception '请输入两个不同的整数比分。';
    end if;
    if p_score_a = p_score_b then
      raise exception '比分不能相同。';
    end if;
    if p_score_a < 0 or p_score_b < 0 or p_score_a > 99 or p_score_b > 99 then
      raise exception '比分需在 0 到 99 之间。';
    end if;
    v_winner := case when p_score_a > p_score_b then v_match.player_a_id else v_match.player_b_id end;
    v_loser  := case when p_score_a > p_score_b then v_match.player_b_id else v_match.player_a_id end;

    select competition_id into v_competition from public.tournaments where id = v_match.tournament_id;

    -- 赛事比赛由 staff 录入；submitted_by 需满足 match_submitter_is_participant 约束，
    -- 因此记为其中一名参赛选手，来源由 source_type='tournament' 标识。
    insert into public.matches (
      played_at, player_a_id, player_b_id, score_a, score_b,
      competition_id, submitted_by, status, source_type, tournament_id, tournament_match_id
    ) values (
      now(), v_match.player_a_id, v_match.player_b_id, p_score_a, p_score_b,
      v_competition, v_match.player_a_id, 'approved', 'tournament', v_match.tournament_id, v_match.id
    ) returning id into v_rating_match_id;
  elsif v_forfeit = 'a' then
    v_winner := v_match.player_b_id;
    v_loser  := v_match.player_a_id;
  elsif v_forfeit = 'b' then
    v_winner := v_match.player_a_id;
    v_loser  := v_match.player_b_id;
  else
    v_winner := null;
    v_loser  := null;
  end if;

  update public.tournament_matches
     set status = 'completed',
         score_a = case when v_forfeit = 'none' then p_score_a else null end,
         score_b = case when v_forfeit = 'none' then p_score_b else null end,
         forfeit = v_forfeit,
         winner_id = v_winner,
         rating_match_id = v_rating_match_id,
         updated_at = now()
   where id = v_match.id;

  if v_winner is not null and v_match.next_match_id is not null then
    if v_match.next_slot = 2 then
      update public.tournament_matches set player_b_id = v_winner, updated_at = now() where id = v_match.next_match_id;
    else
      update public.tournament_matches set player_a_id = v_winner, updated_at = now() where id = v_match.next_match_id;
    end if;
  end if;
  if v_loser is not null and v_match.next_loss_match_id is not null then
    if v_match.next_loss_slot = 2 then
      update public.tournament_matches set player_b_id = v_loser, updated_at = now() where id = v_match.next_loss_match_id;
    else
      update public.tournament_matches set player_a_id = v_loser, updated_at = now() where id = v_match.next_loss_match_id;
    end if;
  end if;
end;
$$;

grant execute on function public.staff_set_tournament_result(uuid, integer, integer, text) to authenticated;
