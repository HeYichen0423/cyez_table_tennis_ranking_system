create or replace function private.current_profile_role()
returns text
language sql
security definer
set search_path = ''
stable
as $$
  select p.role
  from public.profiles p
  where p.id = (select auth.uid())
$$;

create or replace function private.is_staff()
returns boolean
language sql
security definer
set search_path = ''
stable
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and p.is_banned = false
      and p.role in ('admin','moderator')
  )
$$;

create or replace function private.is_admin()
returns boolean
language sql
security definer
set search_path = ''
stable
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and p.is_banned = false
      and p.role = 'admin'
  )
$$;

-- =========================
-- 5) 注册后自动建立 profile
-- =========================
create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, real_name, username)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'real_name'), ''), '未命名选手'),
    lower(trim(new.raw_user_meta_data ->> 'username'))
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

-- =========================
-- 6) 保护账号权限字段
-- 普通用户只能修改自己的 real_name；role / is_banned 只能由 admin 修改。
-- =========================
create or replace function private.protect_profile_fields()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.username is distinct from new.username then
    raise exception '用户名不可修改。';
  end if;

  if old.role is distinct from new.role or old.is_banned is distinct from new.is_banned then
    if (select auth.uid()) is not null and not private.is_admin() then
      raise exception '只有 admin 可以修改账号角色或封禁状态。';
    end if;
    if (select auth.uid()) is not null and old.id = (select auth.uid()) then
      raise exception '为了避免把自己锁在系统外，不能修改自己的角色或封禁状态。';
    end if;
  end if;

  if old.real_name is distinct from new.real_name then
    if old.id <> (select auth.uid()) and not private.is_admin() then
      raise exception '没有权限修改该选手姓名。';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists protect_profile_fields on public.profiles;
create trigger protect_profile_fields
before update on public.profiles
for each row execute function private.protect_profile_fields();

-- =========================
-- 7) 比赛状态与不可变字段保护
-- =========================
create or replace function private.protect_match_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.played_at is distinct from new.played_at
     or old.player_a_id is distinct from new.player_a_id
     or old.player_b_id is distinct from new.player_b_id
     or old.score_a is distinct from new.score_a
     or old.score_b is distinct from new.score_b
     or old.competition_id is distinct from new.competition_id
     or old.submitted_by is distinct from new.submitted_by
  then
    raise exception '比赛核心信息不可修改，如需更正请撤销后重新提交。';
  end if;

  if old.status = 'pending_opponent' then
    if not private.is_staff() then
      if new.status not in ('approved','rejected') then
        raise exception '普通选手只能确认或拒绝待确认比赛。';
      end if;
      if old.player_a_id <> (select auth.uid()) and old.player_b_id <> (select auth.uid()) then
        raise exception '只有比赛双方可以确认比赛。';
      end if;
      if old.submitted_by = (select auth.uid()) then
        raise exception '提交比赛的一方不能自己确认自己的记录。';
      end if;
      if new.status = 'approved' then
        new.opponent_confirmed_at = now();
      end if;
    end if;
  elsif old.status = 'approved' then
    if not private.is_staff() then
      raise exception '已生效的比赛只能由管理员/副管理员撤销。';
    end if;
    if new.status <> 'cancelled' then
      raise exception '已生效比赛只能撤销。';
    end if;
  elsif old.status in ('rejected','cancelled') then
    if old.status <> new.status then
      raise exception '已拒绝或已撤销的比赛不能再次修改。';
    end if;
  end if;

  if new.status in ('approved','rejected','cancelled') and new.reviewed_by is null then
    new.reviewed_by = (select auth.uid());
    new.reviewed_at = now();
  end if;

  return new;
end;
$$;

drop trigger if exists protect_match_update on public.matches;
create trigger protect_match_update
before update on public.matches
for each row execute function private.protect_match_update();

-- 自动记录 admin / moderator 操作
create or replace function private.audit_match_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status is distinct from old.status then
    insert into public.audit_logs(actor_id, action, target_type, target_id, detail)
    values (
      (select auth.uid()),
      case
        when new.status = 'approved' then 'approve_match'
        when new.status = 'rejected' then 'reject_match'
        when new.status = 'cancelled' then 'cancel_match'
        else 'update_match'
      end,
      'match',
      new.id::text,
      jsonb_build_object('old_status', old.status, 'new_status', new.status)
    );
  end if;
  return new;
end;
$$;

drop trigger if exists audit_match_change on public.matches;
create trigger audit_match_change
after update on public.matches
for each row execute function private.audit_match_change();

create or replace function private.audit_profile_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.role is distinct from new.role or old.is_banned is distinct from new.is_banned then
    insert into public.audit_logs(actor_id, action, target_type, target_id, detail)
    values (
      (select auth.uid()),
      'update_account',
      'profile',
      new.id::text,
      jsonb_build_object(
        'old_role', old.role,
        'new_role', new.role,
        'old_banned', old.is_banned,
        'new_banned', new.is_banned
      )
    );
  end if;
  return new;
end;
$$;

drop trigger if exists audit_profile_change on public.profiles;
create trigger audit_profile_change
after update on public.profiles
for each row execute function private.audit_profile_change();

